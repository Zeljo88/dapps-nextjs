import assert from 'node:assert/strict';
import { feedIsFresh, currentSnapshotIsFresh } from '../src/lib/feed-freshness.ts';
import { directoryPeriod, refreshDirectoryPeriod } from '../src/lib/epoch-summary.ts';
import { usableLiveSnapshot, mergeLiveRows } from '../src/lib/live-directory.ts';
import { viewDapp } from '../src/lib/directory-view.ts';

const start=1793483091, now=start+1000;
const status={registryDigest:'reviewed',fresh:true,phase:'running',lastReceivedAt:now-10,lagBlocks:0,checkpoint:{epoch:665,time:now-10}};
assert.equal(feedIsFresh(status,now),true);
for(const changed of [{fresh:false},{phase:'stopped'},{lastReceivedAt:now-180},{lastReceivedAt:now+1},{lastReceivedAt:null},{lagBlocks:11},{lagBlocks:null}])assert.equal(feedIsFresh({...status,...changed},now),false);
assert.equal(feedIsFresh({...status,checkpoint:{...status.checkpoint,time:now-180}},now),false,'A busy collector replaying old blocks is not a current feed');
assert.equal(currentSnapshotIsFresh(now,now+44),true);
assert.equal(currentSnapshotIsFresh(now,now+45),false);
assert.equal(currentSnapshotIsFresh(now+1,now),false);
const summary={current:{epoch:664,startTime:start-432000,endTime:start},previous:null,window:[],previousWindow:[]};
const initial=directoryPeriod(summary,status,now);
const snapshot={generatedAt:now,status,dapps:[{slug:'minswap',observedEpoch:665,observedTxEpoch:7,epochRecordedSince:start}],currentTvl:{}};
assert.equal(usableLiveSnapshot(snapshot,'reviewed',now),snapshot);
assert.equal(usableLiveSnapshot(snapshot,'changed',now),null,'Registry changes require a fresh historical page');
assert.equal(usableLiveSnapshot(snapshot,'reviewed',now+45),null,'A successful response cannot be replayed indefinitely');
assert.equal(usableLiveSnapshot({...snapshot,generatedAt:now+1},'reviewed',now),null);
const rows=[{slug:'minswap',observedEpoch:665,liveTransactions:999,liveSince:start,epochTransactions:100,currentTvl:{current:{usd:10,observedAt:now-86401,epochEnd:now}}}];
assert.equal(mergeLiveRows(rows,null,now)[0].liveTransactions,null,'Do not use cached SSR counters as current observations');
assert.equal(mergeLiveRows(rows,null,now)[0].epochTransactions,100,'Preserve validated completed totals during an outage');
assert.equal(mergeLiveRows(rows,null,now)[0].currentTvl,null,'Cached current TVL also ages out');
assert.equal(viewDapp(mergeLiveRows(rows,snapshot,now)[0],'current',refreshDirectoryPeriod(initial,status,now)).epochTransactions,7);
const rollover=refreshDirectoryPeriod(initial,status,start+432000);
assert.equal(rollover.currentEpoch,666);
assert.equal(rollover.liveAvailable,false,'An old checkpoint cannot cross the epoch boundary');
assert.equal(viewDapp(mergeLiveRows(rows,snapshot,now)[0],'current',rollover).epochTransactions,null);
assert.equal(refreshDirectoryPeriod(initial,null,now).liveAvailable,false);
assert.equal(refreshDirectoryPeriod(initial,{...status,lastReceivedAt:now-180},now).liveAvailable,false);
console.log('Live data checks passed: offline, expiry, future timestamps, registry changes, rollover and immutable completed totals.');
