import assert from "node:assert/strict";
import { epochMetrics, percentageChange, selectEpochPeriod } from "../src/lib/epoch-summary.ts";

const dapp = (transactions, activeWallets, attributionPercent = 100) => ({ slug: "test", name: "Test", transactions, activeWallets, walletActivity: { attributionPercent } });
const epoch = (number, start, end, dapps, passed = true) => ({ epoch: number, startTime: start, endTime: end, dapps, validation: { passed } });
const history = epochs => ({ registryDigest: "reviewed", aggregation: "epoch", coverage: "partial", epochs });
const previous = epoch(9, 0, 10, [dapp(100, 20)]);
const current = epoch(10, 10, 20, [dapp(80, 25, 98.5)]);
const future = epoch(11, 20, 40, [dapp(999, 999)]);
const failed = epoch(12, 20, 30, [dapp(999, 999)], false);
const selected = selectEpochPeriod(history([future, current, previous, failed]), "reviewed", 30);
assert.equal(selected.current.epoch, 10, "Use the newest completed, passed epoch even when responses are unsorted");
assert.equal(selected.previous.epoch, 9);
assert.deepEqual(epochMetrics("test", selected), { epochTransactions: 80, epochWallets: 25, txGrowth: -20, walletGrowth: 25, attributionPercent: 98.5 });
assert.equal(selectEpochPeriod(history([current]), "different", 30), null, "Do not combine registry versions");
assert.equal(selectEpochPeriod(null, "reviewed", 30), null);
assert.equal(selectEpochPeriod(history([]), "reviewed", 30), null);
assert.equal(selectEpochPeriod(history(null), "reviewed", 30), null, "Malformed summaries must not break the live directory");
assert.equal(selectEpochPeriod(history([null, {}]), "reviewed", 30), null);
assert.equal(selectEpochPeriod(history([current, epoch(8, 0, 10, [])]), "reviewed", 30).previous, null, "Do not compare across an epoch gap");
assert.equal(selectEpochPeriod(history([current, epoch(9, 0, 9, [])]), "reviewed", 30).previous, null, "Coverage intervals must be adjacent");
assert.deepEqual(epochMetrics("missing", selected), { epochTransactions: null, epochWallets: null, txGrowth: null, walletGrowth: null, attributionPercent: null });
assert.equal(percentageChange(0, 100), -100);
assert.equal(percentageChange(0, 0), 0);
assert.equal(percentageChange(10, 0), null, "Never invent a percentage from a zero baseline");
assert.equal(percentageChange(null, 10), null);
assert.equal(percentageChange(10, null), null);
const zeros = selectEpochPeriod(history([epoch(9, 0, 10, [dapp(0, 0)]), epoch(10, 10, 20, [dapp(0, 0)])]), "reviewed", 30);
assert.deepEqual(epochMetrics("test", zeros), { epochTransactions: 0, epochWallets: 0, txGrowth: 0, walletGrowth: 0, attributionPercent: 100 });
const missingWallet = selectEpochPeriod(history([previous, epoch(10, 10, 20, [{ slug: "test", transactions: 80 }])]), "reviewed", 30);
assert.equal(epochMetrics("test", missingWallet).epochWallets, null);
assert.equal(epochMetrics("test", missingWallet).walletGrowth, null);
assert.equal(epochMetrics("test", missingWallet).attributionPercent, null);
console.log("Epoch summary regression checks passed: growth, zero counts, missing data, gaps, completion, validation and registry matching.");
