import assert from "node:assert/strict";
import { epochMetrics, sixEpochMetrics, sixEpochComparison, percentageChange, selectEpochPeriod, directoryPeriod } from "../src/lib/epoch-summary.ts";
import { viewDapp } from "../src/lib/directory-view.ts";

const dapp = (transactions, activeWallets, attributionPercent = 100) => ({ slug: "test", name: "Test", transactions, activeWallets, walletActivity: { attributionPercent } });
const epoch = (number, start, end, dapps, passed = true) => ({ epoch: number, startTime: start, endTime: end, dapps, validation: { passed } });
const history = epochs => ({ registryDigest: "reviewed", aggregation: "epoch", coverage: "partial", epochs });
const previous = epoch(9, 0, 10, [dapp(100, 20)]);
const current = epoch(10, 10, 20, [dapp(80, 25, 98.5)]);
const future = epoch(11, 20, 40, [dapp(999, 999)]);
const failed = epoch(12, 20, 30, [dapp(999, 999)], false);
const selected = selectEpochPeriod(history([future, current, previous, failed]), "reviewed", 30);
assert.equal(selected.current.epoch, 10, "Use the newest completed, passed epoch even when responses are unsorted");
assert.equal(selected.previous.epoch, 9);
assert.deepEqual(epochMetrics("test", selected), { epochTransactions: 80, epochWallets: 25, previousTransactions: 100, previousWallets: 20, txGrowth: -20, walletGrowth: 25, attributionPercent: 98.5 });
assert.equal(selectEpochPeriod(history([current]), "different", 30), null, "Do not combine registry versions");
assert.equal(selectEpochPeriod(null, "reviewed", 30), null);
assert.equal(selectEpochPeriod(history([]), "reviewed", 30), null);
assert.equal(selectEpochPeriod(history(null), "reviewed", 30), null, "Malformed summaries must not break the live directory");
assert.equal(selectEpochPeriod(history([null, {}]), "reviewed", 30), null);
assert.equal(selectEpochPeriod(history([current, epoch(8, 0, 10, [])]), "reviewed", 30).previous, null, "Do not compare across an epoch gap");
assert.equal(selectEpochPeriod(history([current, epoch(9, 0, 9, [])]), "reviewed", 30).previous, null, "Coverage intervals must be adjacent");
assert.deepEqual(epochMetrics("missing", selected), { epochTransactions: null, epochWallets: null, previousTransactions: null, previousWallets: null, txGrowth: null, walletGrowth: null, attributionPercent: null });
assert.equal(percentageChange(0, 100), -100);
assert.equal(percentageChange(0, 0), 0);
assert.equal(percentageChange(10, 0), null, "Never invent a percentage from a zero baseline");
assert.equal(percentageChange(null, 10), null);
assert.equal(percentageChange(10, null), null);
const zeros = selectEpochPeriod(history([epoch(9, 0, 10, [dapp(0, 0)]), epoch(10, 10, 20, [dapp(0, 0)])]), "reviewed", 30);
assert.deepEqual(epochMetrics("test", zeros), { epochTransactions: 0, epochWallets: 0, previousTransactions: 0, previousWallets: 0, txGrowth: 0, walletGrowth: 0, attributionPercent: 100 });
const missingWallet = selectEpochPeriod(history([previous, epoch(10, 10, 20, [{ slug: "test", transactions: 80 }])]), "reviewed", 30);
assert.equal(epochMetrics("test", missingWallet).epochWallets, null);
assert.equal(epochMetrics("test", missingWallet).walletGrowth, null);
assert.equal(epochMetrics("test", missingWallet).attributionPercent, null);
const six = Array.from({length:6},(_,i)=>epoch(i+1,i*10,(i+1)*10,[{
  ...dapp(100,i+1),walletActivity:{candidateOrderOutputs:i===0?100:1,attributedOrderOutputs:i===0?50:1},
}]));
const fullWindow=selectEpochPeriod(history(six),'reviewed',100);
assert.equal(fullWindow.window.length,6);
assert.deepEqual(sixEpochMetrics('test',fullWindow),{windowTransactions:600,windowWallets:3.5,windowCoverage:52.38});
assert.equal(fullWindow.previous.epoch,5);
assert.equal(sixEpochMetrics('test',selectEpochPeriod(history(six.slice(1)),'reviewed',100)).windowTransactions,null,'Never present five epochs as six');
assert.equal(sixEpochMetrics('test',selectEpochPeriod(history(six.filter(e=>e.epoch!==3)),'reviewed',100)).windowWallets,null);
assert.equal(sixEpochMetrics('missing',fullWindow).windowTransactions,null);
const seven=selectEpochPeriod(history([...six,epoch(7,60,70,[dapp(50,7)])]),'reviewed',100);
assert.deepEqual(seven.window.map(e=>e.epoch),[2,3,4,5,6,7],'Six completed periods move forward without including an incomplete epoch');
console.log("Epoch summary regression checks passed: growth, zero counts, missing data, gaps, completion, validation and registry matching.");

const twelve=Array.from({length:12},(_,i)=>epoch(i+1,i*432000,(i+1)*432000,[dapp(i<6?100:200,i<6?2:4)]));
const twelvePeriod=selectEpochPeriod(history(twelve),'reviewed',13*432000);
assert.deepEqual(twelvePeriod.window.map(e=>e.epoch),[7,8,9,10,11,12]);
assert.deepEqual(twelvePeriod.previousWindow.map(e=>e.epoch),[1,2,3,4,5,6]);
const sixCompare=sixEpochComparison('test',twelvePeriod);
assert.equal(sixCompare.windowTransactions,1200);
assert.equal(sixCompare.windowWallets,4,'Average per epoch, never a sum of wallet identities');
assert.equal(sixCompare.windowPreviousTransactions,600);
assert.equal(sixCompare.windowPreviousWallets,2);
assert.equal(sixCompare.windowTxGrowth,100);
assert.equal(sixCompare.windowWalletGrowth,100);
assert.equal(sixEpochComparison('test',fullWindow).windowTxGrowth,null,'Six epochs alone cannot produce a previous-six comparison');
const gapTwelve=selectEpochPeriod(history(twelve.filter(e=>e.epoch!==5)),'reviewed',13*432000);
assert.equal(gapTwelve.previousWindow.length,0,'A missing epoch invalidates the comparison window');
assert.equal(sixEpochComparison('test',gapTwelve).windowWalletGrowth,null);
const now=12*432000+100;
const freshStatus={fresh:true,checkpoint:{epoch:13}};
const live=directoryPeriod(twelvePeriod,freshStatus,now);
assert.equal(live.currentEpoch,13);
assert.equal(live.currentStartTime,12*432000);
assert.equal(live.currentEndTime,13*432000);
assert.equal(live.liveAvailable,true);
assert.equal(directoryPeriod(twelvePeriod,{fresh:false,checkpoint:{epoch:13}},now).liveAvailable,false);
assert.equal(directoryPeriod(twelvePeriod,freshStatus,13*432000).currentEpoch,14,'Advance at the exact epoch boundary');
assert.equal(directoryPeriod(twelvePeriod,freshStatus,13*432000).liveAvailable,false,'Never use prior-epoch observations after rollover');
assert.equal(directoryPeriod(null,freshStatus,now).currentEpoch,null,'Do not invent epoch timing without validated history');
const row={...epochMetrics('test',twelvePeriod),...sixCompare,observedEpoch:13,liveTransactions:7,liveSince:now-50};
assert.equal(viewDapp(row,'completed',live),row,'The completed view is the unchanged validated summary');
assert.equal(viewDapp(row,'six',live).epochTransactions,1200);
assert.equal(viewDapp(row,'six',live).epochWallets,4);
assert.equal(viewDapp(row,'six',live).txGrowth,100);
const liveRow=viewDapp(row,'current',live);
assert.equal(liveRow.epochTransactions,7);
assert.equal(liveRow.epochWallets,null,'Current wallets must remain pending');
assert.equal(liveRow.txGrowth,null,'Never compare a partial epoch to a complete epoch');
assert.equal(liveRow.walletGrowth,null);
assert.equal(viewDapp({...row,observedEpoch:12},'current',live).epochTransactions,null);
assert.equal(viewDapp(row,'current',{...live,liveAvailable:false}).epochTransactions,null);
assert.equal(viewDapp(row,'current',{...live,liveAvailable:false}).liveSince,null);
console.log('Directory period checks passed: matching six-epoch comparisons, averaging, pending wallets, freshness and rollover.');
