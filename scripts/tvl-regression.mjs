import assert from "node:assert/strict";
import { selectEpochTvl, listedTvlTotal } from "../src/lib/tvl-summary.ts";

const end=1793483091, previousEnd=end-5*86400, now=end+86400;
const point=(date,totalLiquidityUSD)=>({date,totalLiquidityUSD});
const payload=points=>({id:"1494",chainTvls:{Cardano:{tvl:points},"Cardano-staking":{tvl:[point(end,999999)]}},tvl:[point(end,888888)]});
const points=[point(end+1,999),point(end-78291,13973556),point(previousEnd-78291,14593389)];
const selected=selectEpochTvl("minswap",payload(points),end,previousEnd,now);
assert.deepEqual(selected.current,{usd:13973556,observedAt:end-78291,epochEnd:end},"Use a pre-boundary Cardano snapshot, never a future value or staking/global aggregate");
assert.equal(selected.previous.usd,14593389);
assert.equal(selected.sourceUrl,"https://defillama.com/protocol/minswap-dex");
assert.deepEqual(selectEpochTvl("minswap",payload([...points].reverse()),end,previousEnd,now),selected,"Response order must not change the chosen observation");
assert.equal(selectEpochTvl("minswap",payload([point(end-86401,10)]),end,previousEnd,now).current,null,"Fail closed when the pre-boundary snapshot is older than a day");
assert.equal(selectEpochTvl("minswap",payload([point(end+1,10)]),end,null,now).current,null,"Do not use future observations");
assert.equal(selectEpochTvl("minswap",payload([point(end,0)]),end,null,now).current.usd,0,"Keep genuine zero TVL");
assert.equal(selectEpochTvl("minswap",payload([point(end,-1),point(end,"10"),point(end,Infinity),null]),end,null,now).current,null,"Invalid values cannot become TVL");
assert.equal(selectEpochTvl("minswap",payload([point(end,1),point(end,2)]),end,null,now),null,"Conflicting duplicates are not trustworthy");
assert.equal(selectEpochTvl("minswap",{id:"parent#minswap",chainTvls:{Cardano:{tvl:points}}},end,null,now),null,"Fail closed when provider protocol identity changes");
assert.equal(selectEpochTvl("minswap",{id:"1494",tvl:points},end,null,now),null,"Require the explicit Cardano series");
assert.equal(selectEpochTvl("not-reviewed",payload(points),end,null,now),null);
assert.equal(selectEpochTvl("__proto__",payload(points),end,null,now),null);
assert.equal(selectEpochTvl("minswap",payload(points),end,null,end-1),null,"Only use completed epochs");
assert.equal(selectEpochTvl("minswap",payload(points),end,end+1,now).previous,null);
assert.equal(selectEpochTvl("minswap",null,end,null,now),null);
assert.equal(listedTvlTotal([selected,selected]),27947112);
assert.equal(listedTvlTotal([selected,null]),null,"A missing protocol must not make a partial sum look complete");
assert.equal(listedTvlTotal([]),null);
assert.equal(listedTvlTotal([selected,{...selected,current:{...selected.current,observedAt:end}}]),null,"Do not sum balances from different times");
console.log("TVL regression checks passed: provider identity, Cardano-only series, epoch snapshots, missing/stale/invalid values and matched aggregate times.");
